export const COUNTRIES = COUNTRIES_200;
export const FLAGS_PER_MATCH = 50;
export const TOTAL_FLAGS = COUNTRIES_200.length; // 211 countries
export const MATCHES_PER_CYCLE = Math.floor(TOTAL_FLAGS / FLAGS_PER_MATCH); // 4 matches per cycle

// Shuffled cycle caches so each match gets a distinct group of 50 flags without repeating
const cycleCache = new Map<number, CountryData[]>();

function getShuffledCycle(cycleIdx: number): CountryData[] {
  if (!cycleCache.has(cycleIdx)) {
    const pool = [...COUNTRIES_200];
    // Fisher-Yates random shuffle of the entire master pool
    for (let i = pool.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [pool[i], pool[j]] = [pool[j], pool[i]];
    }
    cycleCache.set(cycleIdx, pool);
  }
  return cycleCache.get(cycleIdx)!;
}

/**
 * Returns exactly 50 flags for the given 1-based match number.
 * Cycles indefinitely through the master pool.
 * If previousChampionId is supplied, the previous champion is strictly
 * removed/excluded from the new match.
 */
export function getMatchFlags(
  matchNumber: number,
  previousChampionId?: string | null
): {
  flags: CountryData[];
  matchInCycle: number;
  totalInCycle: number;
  cycleNumber: number;
} {
  const zeroBasedMatch = Math.max(0, matchNumber - 1);
  const cycleNumber = Math.floor(zeroBasedMatch / MATCHES_PER_CYCLE) + 1;
  const matchInCycle = (zeroBasedMatch % MATCHES_PER_CYCLE) + 1;

  const dataset = getShuffledCycle(cycleNumber);
  const startIdx = (matchInCycle - 1) * FLAGS_PER_MATCH;
  const endIdx = startIdx + FLAGS_PER_MATCH;
  let flags = dataset.slice(startIdx, endIdx);

  // Guarantee exactly 50 flags even if near end of slice
  if (flags.length < FLAGS_PER_MATCH) {
    const existingIds = new Set(flags.map((f) => f.id.toLowerCase()));
    for (const c of dataset) {
      if (!existingIds.has(c.id.toLowerCase())) {
        flags.push(c);
        existingIds.add(c.id.toLowerCase());
        if (flags.length === FLAGS_PER_MATCH) break;
      }
    }
  }

  // Remove previous champion from the new match if present
  if (previousChampionId) {
    const prevId = previousChampionId.toLowerCase();
    const champIdx = flags.findIndex((f) => f.id.toLowerCase() === prevId);
    if (champIdx !== -1) {
      const selectedIds = new Set(flags.map((f) => f.id.toLowerCase()));
      // Pick a replacement from the master pool that is not in the match and not the champion
      const replacement = COUNTRIES_200.find(
        (c) => !selectedIds.has(c.id.toLowerCase()) && c.id.toLowerCase() !== prevId
      );
      if (replacement) {
        flags = [...flags];
        flags[champIdx] = replacement;
      }
    }
  }

  return {
    flags,
    matchInCycle,
    totalInCycle: MATCHES_PER_CYCLE,
    cycleNumber,
  };
}
